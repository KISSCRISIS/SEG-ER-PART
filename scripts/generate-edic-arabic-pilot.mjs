// --- Full Audit ---
const reRead = readFileSync('./pilot-edic-arabic.jsonl', 'utf8').trim().split('\n');
const data = reRead.map(l => { try { return JSON.parse(l) } catch(e) { return null } }).filter(Boolean);

let allValid = true;
let auditIssues = [];

const origMap = new Map();
for (const line of pilotQuestions) {
  const o = JSON.parse(line);
  origMap.set(o.id, o);
}

for (const q of data) {
  const ar = q.arabicExplanation;
  const prefix = ar.match(/^[^:]+:/);
  const prefixName = prefix ? prefix[0] : 'none';
  const orig = origMap.get(q.id);

  if (!approvedPrefixes.includes(prefixName)) {
    auditIssues.push({ q: q.id, rule: 'Invalid prefix', detail: prefixName });
    allValid = false;
  }

  const prefixWords = prefixName.replace(':', '').split(/\s+/);
  if (prefixWords.length > 2) {
    auditIssues.push({ q: q.id, rule: 'Prefix too long', detail: prefixName });
    allValid = false;
  }

  if (!/\([^)]+\)/.test(ar)) {
    auditIssues.push({ q: q.id, rule: 'Missing English terms in parentheses' });
    allValid = false;
  }

  if (ar.length < 300 || ar.length > 550) {
    auditIssues.push({ q: q.id, rule: 'Length violation', detail: `${ar.length} chars` });
    allValid = false;
  }

  if (orig && orig.englishExplanation !== q.englishExplanation) {
    auditIssues.push({ q: q.id, rule: 'English explanation modified' });
    allValid = false;
  }

  if (orig && orig.question !== q.question) {
    auditIssues.push({ q: q.id, rule: 'Question text modified' });
    allValid = false;
  }

  if (orig && orig.correctAnswerKey !== q.correctAnswerKey) {
    auditIssues.push({ q: q.id, rule: 'correctAnswerKey modified' });
    allValid = false;
  }
}

